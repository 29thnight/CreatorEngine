#pragma once
#include "AuthoringReadNode.h"

// SerializationPlan D3-a-1 — 저작 노드의 **구조적 동등성** 판정.
//
// 왜 별도 함수인가: 지금까지 "두 값이 같은가"를 `YAML::Dump(a) == YAML::Dump(b)`로
// 물었다(§3.3, Y-6). 그 방식의 문제는 둘이다.
//
//   ① 비교하려고 문자열을 만든다. 프로퍼티 하나당 emitter를 두 번 돌리고 std::string
//      두 개를 할당한다 — 비교에 필요 없는 일이다.
//   ② **표기에 민감하다.** 같은 값이라도 맵 키 순서나 emitter 스타일(flow/block)이
//      다르면 다른 문자열이 나온다. 프리팹 오버라이드 시딩에서 이는 거짓 양성이 된다 —
//      바꾼 적 없는 프로퍼티가 "오버라이드됨"으로 기록된다.
//
// ★ 그래서 이 함수는 Dump 비교의 **동작을 그대로 옮기지 않는다.** 맵을 순서 무관으로
//   비교하는 것이 의도된 차이이며, ①은 부수적 이득이고 ②가 본래 목적이다. 이 차이는
//   `serialize.nodeequal` 자가 검사가 명시적으로 단정한다.
//
// 이 파일은 나중에 `AuthoringArchive`의 구조 비교로 흡수된다(§3.3). 지금은 backend
// 타입 대신 단일 ryml 읽기 경계인 `ReadNode`만 받는다.
namespace Authoring
{
	// 두 노드가 같은 값을 나타내는가.
	//
	// 판정 규칙:
	//   · 정의되지 않음/널  — 둘 다 그러하면 같다.
	//   · 스칼라            — 문자열 표현이 같으면 같다(타입 없는 YAML 스칼라의 정본).
	//   · 시퀀스            — 길이가 같고 **같은 순서로** 각 원소가 같으면 같다.
	//   · 맵                — 키 집합이 같고 각 키의 값이 같으면 같다. **순서는 보지 않는다.**
	//
	// 시퀀스는 순서가 값의 일부이므로 순서를 본다. 맵은 아니다 — 이 비대칭이 이
	// 함수의 요점이다.
	[[nodiscard]] bool NodesEqual(const ReadNode& lhs, const ReadNode& rhs);
}
