#pragma once
// 선언된 창의 프레임 소유자 (PHASE 21 M4 · 계획서 부록 B.3).
//
// ── 이 파일만 ImGui를 안다 ────────────────────────────────────────────────
//
// 표면·표기·표는 std만 의존한다(M0이 메뉴에서 세운 것과 같은 층 구성). ImGui
// 번역은 여기 한 곳에 모은다. 그래서 `window_trait` 열거자를 늘리면 아래
// 번역 switch가 함께 막아 서고, 새 성질이 조용히 무시되지 않는다.
//
// ── 셸이 Begin/End를 소유하는 이유 ────────────────────────────────────────
//
// 지금은 창마다 자기 `Begin`을 부른다. 그래서 `NoSavedSettings`를 빠뜨린 창,
// `End`를 조건부로 부르는 창, 표시 이름을 그대로 id로 쓰는 창이 섞여 있고
// 배치가 이름 변경 한 번에 깨진다(계획서 §1.4). 프레임을 셸이 소유하면
// `표시 이름###고정 ID` 규칙과 플래그 규약이 **한 자리에서** 강제된다.
//
// 본문은 `void draw()` 하나이고 `Begin`/`End`를 부르지 않는다. 그 규약은
// 컴파일로 강제할 수 없어 이관 게이트가 맡는다(M4 4단계).

#include <string>

namespace editor
{
    /// 표에 실린 창을 선언 순서대로 그린다. 표가 비어 있으면 아무것도 하지 않는다.
    /// 도크스페이스를 세운 **뒤**, 프레임이 끝나기 전에 한 번 부른다.
    void draw_declared_windows();

    /// `editor.windows` 덤프의 몸통. 창 하나가 한 줄이고 아홉 자리를 적는다.
    /// 게이트가 이 문자열을 읽으므로 열은 늘리기만 하고 줄이지 않는다.
    std::string dump_declared_windows();
}
