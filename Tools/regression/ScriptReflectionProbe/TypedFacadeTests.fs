module TypedFacadeTests

open System
open System.Text.Json
open CreatorEngine
open CreatorEngine.ProbeNativeTypes

let run (check: bool -> string -> unit) (rejected: (unit -> unit) -> string -> string) (entity: Entity) =
    // Every member below is generated from the same libclang declarations as
    // native registration. The test does not spell native member paths.
    let view = reflection_probe_ComponentView.From(entity)
    view.title <- "컴포넌트별 F# 🎹"
    check (view.title = "컴포넌트별 F# 🎹" && view.TitleView() = view.title) "generated component string members and string view method"
    view.settings.count <- 81
    check (view.settings.ReadCount() = 81 && view.settings.Add(2) = 83) "generated nested typed fields and methods"
    check (view.BaseValue() = view.inherited) "generated inherited members"
    check (view.Choose(2) = 12 && view.Choose(2.0f) = 22) "generated F# overloads remain distinct"
    let mutable argument = 4
    view.Adjust(&argument)
    check (argument = 87) "generated byref parameter receives native writeback"
    let mutable buffer = NativeArray<int>.FromArray([|1;2;3|], NativeCodecs.Int32)
    check (view.FillSpan(&buffer) = 3 && buffer.ToArray() = [|11;12;13|]) "generated mutable span receives native output snapshot"
    let mutable records = NativeArray<reflection_probe_SettingsView>.FromArray(
        [|reflection_probe_SettingsView.Create(20, 0.25f, "record input")|], reflection_probe_SettingsView.Codec)
    view.FillSettings(&records)
    check (records.Count = 1 && records.[0].count = 21 && records.[0].label = "record input") "generated typed record array input and mutable output"
    let mutable emptyRecords = NativeArray<reflection_probe_SettingsView>.Empty(reflection_probe_SettingsView.Codec)
    view.FillSettings(&emptyRecords)
    check (emptyRecords.Count = 0) "generated typed empty record array input"
    check (view.Echo("문자열") = "문자열" && view.EchoView("view") = "view" && view.EchoCString("cstring") = "cstring") "generated string parameter codecs"
    let before = view.calls
    check (view.Increase(1) = 84 && view.calls = before + 1) "generated mutating method executes exactly once"

    let aliased = reflection_probe_AliasedView.Create(96)
    check (aliased.count = 96 && aliased.ReadJson().GetProperty("wire_count").GetInt32() = 96) "generated snapshot constructor honors serialized alias"
    let echoed = view.EchoAliased(aliased)
    check (echoed.count = 96 && echoed.With_count(97).count = 97) "generated aliased record argument and return"
    rejected (fun () -> echoed.count <- 1) "generated record return cannot mutate detached snapshot" |> ignore
    let position = math_vector3View.Create(3.0f, 4.0f, 5.0f)
    let echoedPosition = view.EchoDirection(position)
    check (echoedPosition.x = 3.0f && echoedPosition.y = 4.0f && echoedPosition.z = 5.0f) "generated native math argument and return"
    view.direction.x <- 6.0f
    check (view.direction.x = 6.0f) "generated native math child mutation"
    rejected (fun () -> view.lockedDirection.x <- 9.0f) "generated readonly math child remains readonly" |> ignore
    let detached = view.SnapshotSettings()
    check (detached.count = 84 && detached.With_count(99).count = 99 && view.settings.count = 84) "generated detached snapshot copy leaves native state unchanged"
    rejected (fun () -> detached.count <- 1) "generated detached settings remains read-only" |> ignore
    view.GetSettings().count <- 85
    check (view.settings.count = 85) "generated reference getter remains live"
    rejected (fun () -> view.GetReadOnlySettings().count <- 1) "generated const reference cannot become mutable" |> ignore
    view.GetShared().Value.count <- 86
    check (view.shared.Value.count = 86) "generated retained owner getter keeps typed nested access"
    rejected (fun () -> view.lockedShared.Value.count <- 1) "generated readonly ownership wrapper retains constness" |> ignore

    view.engineItems.[0].count <- 87
    view.engineNamed.["엔진"].count <- 88
    check (view.engineItems.[0].count = 87 && view.engineNamed.["엔진"].count = 88) "generated actual engine containers expose typed record elements"
    check (view.engineNamed.TryGetValue("missing").IsNone) "generated map TryGetValue validates a lazy record path"
    view.``fixed``.[0] <- 8
    check (view.``fixed``.[0] = 8) "generated fixed array mutation"
    check (view.readonlySet.[0] = 3) "generated set exposes readable indexed elements"
    rejected (fun () -> view.readonlySet.[0] <- 4) "generated set elements remain read-only" |> ignore
    rejected (fun () -> view.bits.[0] <- false) "generated packed bool proxy cannot expose mutable storage" |> ignore
    view.absent.Set(reflection_probe_SettingsView.Create(89, 0.5f, "optional"))
    check (view.absent.HasValue && view.absent.Value.count = 89) "generated optional constructs an explicit typed value"
    view.absent.Clear()
    check (view.absent.TryValue.IsNone) "generated optional clear"
    check (view.tuple.Item1 = 6 && view.tuple.Item2.count = 38 && view.tuple.Item3 = "tuple") "generated heterogeneous tuple"
    view.choice.SetCase1(reflection_probe_SettingsView.Create(90, 0.25f, "case"))
    check (view.choice.Case1.Value.count = 90 && view.choice.Case2.IsNone) "generated typed variant record selection"
    view.SwitchChoice()
    check (view.choice.Case2 = Some 91) "generated variant discriminator after native method"
    view.outcome.SetError(reflection_probe_SettingsView.Create(93, 0.25f, "error"))
    check (view.outcome.Error.count = 93 && not view.outcome.IsSuccess) "generated expected error graph"
    view.SucceedOutcome()
    check (view.outcome.Value = 92) "generated expected success graph"
    check (view.RawArgument_Unavailable.Reason.Contains("pointer")) "unsafe native member has explicit generated reason"
    let cycleBefore = view.cycle.value
    let callsBeforeCycle = view.calls
    view.UnsafeRecord(view.cycle)
    check (view.cycle.value = cycleBefore + 1 && view.calls = callsBeforeCycle + 1) "generated pointer-bearing record input binds native identity instead of serializing its cycle"
    let detachedCycle = reflection_probe_CycleView(NativeTypeView.FromSnapshot(
        JsonSerializer.SerializeToElement(dict [ "value", box 9; "next", null ])))
    let beforeDetachedCycle = view.calls
    rejected (fun () -> view.UnsafeRecord(detachedCycle)) "generated pointer-bearing record rejects detached identity" |> ignore
    check (view.calls = beforeDetachedCycle && view.cycle.value = cycleBefore + 1) "detached native record rejection occurs before effects"

    let beforeCreate = view.calls
    let created = view.CreateSettings(101)
    check (not created.IsLive && created.Value.count = 101 && view.calls = beforeCreate + 1) "generated mutating pointer result is an immediate detached snapshot"
    check (created.Value.count = 101 && created.Value.label = "nested" && view.calls = beforeCreate + 1) "reading a mutating method result never replays native invocation"
    rejected (fun () -> created.Value.count <- 102) "generated mutating pointer result cannot become a live writable alias" |> ignore
    view.UpdateNativeSettings(view.shared, 103)
    check (view.shared.Value.count = 103 && view.ReadNativeSettings(view.shared) = 103) "generated pointer arguments bind a live typed pointee"
    check (view.ReadNativeSettings(view.missingSettings) = -1) "generated native pointer parameter preserves typed null"
    check (created.Value.count = 101) "native changes do not rewrite the retained result snapshot"
    let beforeDetached = view.calls
    rejected (fun () -> view.UpdateNativeSettings(created, 104)) "generated raw pointer parameter rejects detached snapshot" |> ignore
    rejected (fun () -> view.BindSharedSettings(created)) "generated owner parameter rejects detached snapshot" |> ignore
    check (view.calls = beforeDetached && view.shared.Value.count = 103) "detached pointer and owner arguments fail before native mutation"
    let beforeReadonly = view.calls
    let readonlyCount = view.lockedShared.Value.count
    check (view.ReadNativeSettings(view.lockedShared) = readonlyCount) "const pointer parameter accepts a readonly native owner target"
    rejected (fun () -> view.UpdateNativeSettings(view.lockedShared, 105)) "generated raw pointer parameter preserves readonly pointee access" |> ignore
    rejected (fun () -> view.BindSharedSettings(view.lockedShared)) "readonly owner cannot be copied into a writable alias" |> ignore
    check (view.calls = beforeReadonly && view.lockedShared.Value.count = readonlyCount) "readonly native arguments fail before effects"
    view.BindSharedSettings(view.shared)
    check (view.calls = beforeReadonly + 1 && view.shared.Value.count = 103) "generated owner argument binds the native owner wrapper"
    let beforeRemove = view.calls
    view.RemoveNativeSettings(view.shared)
    check (view.calls = beforeRemove + 1 && not view.shared.HasValue) "native deletion executes once without reading a destroyed argument afterward"
    check (view.ReadNativeSettings(view.shared) = -1) "generated nullable pointer input accepts an empty typed native owner"
    check (created.Value.count = 101) "detached result remains valid after the native target is destroyed"
    view.ResetShared()
    let beforeTake = view.calls
    let taken = view.TakeShared()
    check (not taken.IsLive && taken.Value.count = 7 && not view.shared.HasValue && view.calls = beforeTake + 1) "script_once native owner method uses one-shot snapshot invocation"
    let takeSpec = NativeMethodSpec("ProbeComponent", "TakeShared", false, [||], [||])
    rejected (fun () -> view.Borrow(takeSpec).ReadJson() |> ignore) "script_once native method cannot be replayed as a getter path" |> ignore
    check (taken.Value.count = 7 && view.calls = beforeTake + 1) "script_once result reads and rejected borrowing never reinvoke the method"
    view.ResetShared()

    // A mixed native/value call must retain output values while omitting the
    // external native argument slots that a mutating method may invalidate.
    let adjust = NativeMethodSpec("ProbeComponent", "Adjust", true, [|"int"|], [|"mutable_reference"|])
    let adjusted = view.InvokeBound(adjust, [|NativeCallArgument.FromJson(NativeCodecs.Int32.Encode(5))|])
    check (adjusted.Arguments.[0].GetInt32() = view.settings.count + 5) "bound invocation preserves mutable JSON reference output"

    // Argument-bearing const lookup is a retained, read-only live path. It is
    // re-evaluated once for a value access, and arguments are checked first.
    let lookup = view.FindSettings("alpha")
    let expected = view.named.["alpha"].count
    let beforeLookup = view.lookupCalls
    check (lookup.Value.count = expected && view.lookupCalls = beforeLookup + 1) "generated const lookup executes once per resolved access"
    rejected (fun () -> lookup.Value.count <- 1) "generated argument lookup cannot expose writable native memory" |> ignore
    check (not (view.FindSettings("missing").HasValue)) "generated const lookup preserves null result"
    let beforeBoundLookup = view.lookupCalls
    rejected (fun () -> view.ReadNativeSettings(lookup) |> ignore) "native binding paths cannot replay a getter during argument resolution" |> ignore
    check (view.lookupCalls = beforeBoundLookup) "rejected getter binding never executes the getter"
    let lookupSpec = NativeMethodSpec("ProbeComponent", "FindSettings", true, [|"std::string"|], [|"const_reference"|])
    let beforeMalformed = view.lookupCalls
    let malformed = view.Borrow(lookupSpec, [| NativeCodecs.Int32.Encode(1) |])
    rejected (fun () -> malformed.Dereference().ReadJson() |> ignore) "typed lookup rejects malformed arguments before invoking" |> ignore
    check (view.lookupCalls = beforeMalformed) "malformed typed lookup never invokes native method"
    let retained = view.GetSettings()
    fun () -> retained.count |> ignore
